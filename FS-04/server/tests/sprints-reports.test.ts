import { beforeAll, describe, expect, it } from "vitest";
import { api, createIssue, createProject, createWorkspace, signup, type TestUser } from "./helpers.js";

describe("sprints and reports", () => {
  let owner: TestUser;
  let slug: string;
  let p: Awaited<ReturnType<typeof createProject>>;

  beforeAll(async () => {
    owner = await signup("Owner");
    slug = (await createWorkspace(owner)).slug;
    p = await createProject(owner, slug, "APP");
  });

  it("runs a full sprint lifecycle and generates a report", async () => {
    const o = api(owner);
    const s1 = (await o.post(`/workspaces/${slug}/sprints`, { projectId: p.project.id, name: "Sprint 1", goal: "Ship login" })).body.sprint;
    const s2 = (await o.post(`/workspaces/${slug}/sprints`, { projectId: p.project.id, name: "Sprint 2" })).body.sprint;

    const issues = await Promise.all([1, 2, 3, 5].map((pts) => createIssue(owner, slug, p.project.id, { storyPoints: pts })));
    const add = await o.post(`/workspaces/${slug}/sprints/${s1.id}/issues`, { issueIds: issues.map((i) => i.id) });
    expect(add.body.updated).toBe(4);

    expect((await o.post(`/workspaces/${slug}/sprints/${s1.id}/start`)).status).toBe(200);
    // only one active sprint per project
    expect((await o.post(`/workspaces/${slug}/sprints/${s2.id}/start`)).status).toBe(400);

    const done = p.workflow.statuses.find((s) => s.category === "DONE")!.id;
    await o.post(`/workspaces/${slug}/issues/${issues[0].id}/move`, { statusId: done });
    await o.post(`/workspaces/${slug}/issues/${issues[3].id}/move`, { statusId: done });

    const board = await o.get(`/workspaces/${slug}/projects/${p.project.id}/boards/${p.boards[0].id}?sprintId=active`);
    expect(board.body.activeSprint.id).toBe(s1.id);
    expect(board.body.columns.flatMap((c: any) => c.issues)).toHaveLength(4);

    const complete = await o.post(`/workspaces/${slug}/sprints/${s1.id}/complete`, { moveOpenIssuesTo: s2.id });
    expect(complete.status).toBe(200);
    expect(complete.body.movedOpenIssues).toBe(2);

    const sprints = (await o.get(`/workspaces/${slug}/sprints?projectId=${p.project.id}`)).body.sprints;
    expect(sprints.find((s: any) => s.id === s2.id).issueCount).toBe(2);

    // Report was generated by the background job (inline in tests).
    const report = (await o.get(`/workspaces/${slug}/reports/${complete.body.reportId}`)).body.report;
    expect(report.status).toBe("COMPLETED");
    expect(report.data.totals.done).toBe(2);
    expect(report.data.points).toEqual({ committed: 6, completed: 6 }); // open issues moved out, done ones remain
    expect(report.data.totals.completionRate).toBe(100);

    const csv = await o.get(`/workspaces/${slug}/reports/${report.id}/csv`);
    expect(csv.headers["content-type"]).toContain("text/csv");
    expect(csv.text.split("\n")[0]).toBe("key,title,status,category,assignee,points,resolvedAt");
  });

  it("generates an on-demand project report", async () => {
    const res = await api(owner).post(`/workspaces/${slug}/reports`, { projectId: p.project.id });
    expect(res.status).toBe(202);
    expect(res.body.report.status).toBe("COMPLETED");
    expect(res.body.report.data.totals.issues).toBe(4);
    expect(res.body.report.data.byStatus.length).toBeGreaterThan(0);
    const list = await api(owner).get(`/workspaces/${slug}/reports?projectId=${p.project.id}`);
    expect(list.body.reports.length).toBe(2);
  });

  it("refuses to add issues to completed sprints or delete active ones", async () => {
    const sprints = (await api(owner).get(`/workspaces/${slug}/sprints?state=COMPLETED`)).body.sprints;
    const issue = await createIssue(owner, slug, p.project.id);
    expect((await api(owner).patch(`/workspaces/${slug}/issues/${issue.id}`, { sprintId: sprints[0].id })).status).toBe(400);
    const s = (await api(owner).post(`/workspaces/${slug}/sprints`, { projectId: p.project.id, name: "S3" })).body.sprint;
    // Sprint 2 is not active yet, so S3 cannot be started while... no sprint is active: start succeeds.
    expect((await api(owner).post(`/workspaces/${slug}/sprints/${s.id}/start`)).status).toBe(200);
    expect((await api(owner).delete(`/workspaces/${slug}/sprints/${s.id}`)).status).toBe(400);
  });
});
